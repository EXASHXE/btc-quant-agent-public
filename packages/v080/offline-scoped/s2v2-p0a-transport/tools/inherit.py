"""Generate the narrow, auditable adaptation of the two accepted source wheels."""

import argparse
import ast
import hashlib
import json
import textwrap
from pathlib import Path
from zipfile import ZipFile

HERE = Path(__file__).resolve().parents[1]
CODE = HERE.parents[1]
OUT = HERE / "S2V2_RELEASE_BOUND_IMPLEMENTATION/src/quant_s2rb"


def archive(package):
    for row in (HERE / "tools/wheels.lock").read_text().splitlines():
        _, expected, filename = row.split(" ", 2)
        path = CODE / filename
        if path.name.startswith(package + "-"):
            assert hashlib.sha256(path.read_bytes()).hexdigest() == expected
            return ZipFile(path)
    raise ValueError(package)


def node(source, name):
    tree = ast.parse(source)
    return next(item for item in tree.body if getattr(item, "name", None) == name)


def exact(source, item):
    return textwrap.dedent(ast.get_source_segment(source, item, padded=True))


def swap(text, before, after):
    assert text.count(before) == 1, before
    return text.replace(before, after)


def inherited():
    with archive("quant_s2v2_offline") as wheel:
        protocol = wheel.read("quant_s2v2/protocol.py").decode()
        console = wheel.read("quant_s2v2/console.py").decode()
    with archive("quant_personal_live_public_b5") as wheel:
        egress = wheel.read("quant_personal_live_public_b5/egress.py").decode()
    cfg = node(protocol, "Configuration")
    read = exact(protocol, next(item for item in cfg.body if getattr(item, "name", None) == "read"))
    read = swap(read, "def read(cls, path):", "def read_config(path, evidence):")
    read = swap(read, 'raw["evidence"] == EVIDENCE', 'raw["evidence"] == evidence')
    read = swap(read, "return cls(", "return Configuration(")
    grant = exact(protocol, node(protocol, "verify_grant"))
    grant = swap(
        grant,
        "def verify_grant(raw, config):",
        "def check_envelope(raw, config, *, schema, domain, evidence):",
    )
    grant = swap(grant, 'raw["schema"] == SCHEMA', 'raw["schema"] == schema')
    grant = swap(grant, "DOMAIN + canonical", "domain + canonical")
    grant = swap(
        grant,
        "(PROFILE, CAPABILITY, EVIDENCE, AUTHORITY)",
        "(PROFILE, CAPABILITY, evidence, AUTHORITY)",
    )
    identity = exact(protocol, node(protocol, "runtime_identity"))
    identity = swap(identity, "    fixture_namespace()\n", "")
    identity = swap(identity, "FIXTURE_RUNTIME_UID_GID_MISMATCH", "RUNTIME_UID_GID_MISMATCH")
    confirm = exact(console, node(console, "confirm"))
    confirm = swap(
        confirm,
        "SYNTHETIC_QA_ONLY {grant.scope['authority']}",
        "{grant.scope['evidence']} {grant.scope['authority']}",
    )
    dns = exact(egress, node(egress, "_dns_answers"))
    dns = swap(
        dns, "def _dns_answers(packet, query_id):", "def dns_answers(packet, query_id, hostname):"
    )
    dns = swap(dns, 'HOST.encode("ascii")', 'hostname.encode("ascii")')
    # Keep the legacy implementation under its own package name and error semantics.
    imports = """# Generated by tools/inherit.py from pinned S2 V2 and B5.post3 wheels.
# ruff: noqa
import hmac
import ipaddress
import os
import secrets
import select
import struct
import subprocess
import termios
import time
from pathlib import Path

from cryptography.exceptions import InvalidSignature
from cryptography.hazmat.primitives.asymmetric.ed25519 import Ed25519PublicKey
from quant_s2v2 import CAPABILITY, PROFILE
from quant_s2v2.console import tty_check
from quant_s2v2.protocol import (
    AUTHORITY, GETS, WINDOW_MS, Configuration, Grant, Pin, canonical, digest,
    fields, file_bytes, hexdigest, integer, require, sha, strict_json,
)
DNS_LIMIT = 4096
"""
    functions = [
        read,
        grant,
        identity,
        confirm,
        exact(egress, node(egress, "route_fingerprint")),
        exact(egress, node(egress, "_name")),
        dns,
    ]
    return imports + "\n\n" + "\n\n\n".join(functions) + "\n"


def dependency_manifest():
    modules = {
        "quant_s2v2": "quant_s2v2_offline",
        "quant_personal_public_b1": "quant_personal_public_b1",
        "quant_personal_public_bridge_b4": "quant_personal_public_bridge_b4",
        "cryptography": "cryptography",
    }
    result = {}
    for module, dist in modules.items():
        with archive(dist) as wheel:
            prefix = module + "/"
            result[module] = {
                n.removeprefix(prefix): hashlib.sha256(wheel.read(n)).hexdigest()
                for n in wheel.namelist()
                if n.startswith(prefix) and Path(n).suffix in {".py", ".json", ".so"}
            }
    return json.dumps(result, sort_keys=True, indent=2) + "\n"


if __name__ == "__main__":
    parser = argparse.ArgumentParser()
    parser.add_argument("--check", action="store_true")
    args = parser.parse_args()
    for name, contents in {
        "_inherited.py": inherited(),
        "dependency_hashes.json": dependency_manifest(),
    }.items():
        path = OUT / name
        if args.check:
            assert path.read_text() == contents, f"inherited source or pin drift: {path}"
        else:
            path.write_text(contents)
